/** 出所の表示（全レシピ共通）。 */
export const RECIPE_SOURCE_NOTE = "Irori 独自作成"

type NumericUnit = Exclude<UnitId, "to_taste" | "pinch">

interface IngredientExtra {
  optional?: boolean
  note?: string
}

function ing(
  ingredientId: CatalogIngredientId,
  amount: number,
  unit: NumericUnit,
  extra: IngredientExtra = {},
): RecipeIngredient {
  return { ingredientId, quantity: { amount, unit }, ...extra }
}

/** 少々。 */
function pinch(
  ingredientId: CatalogIngredientId,
  extra: IngredientExtra = {},
): RecipeIngredient {
  return { ingredientId, quantity: { amount: null, unit: "pinch" }, ...extra }
}

/** 適量。 */
function toTaste(
  ingredientId: CatalogIngredientId,
  extra: IngredientExtra = {},
): RecipeIngredient {
  return { ingredientId, quantity: { amount: null, unit: "to_taste" }, ...extra }
}

/** 2 歳以降の幼児向けの取り分け案内。 */
function toddlerServing(
  guide: Omit<ChildServingGuide, "stage" | "minAgeMonths">,
): ChildServingGuide {
  return { stage: "toddler_2y_plus", minAgeMonths: 24, ...guide }
}

interface RecipeSeed {
  id: string
  title: string
  role: DishRole
  minutes: number
  includesStaple?: boolean
  ingredients: readonly RecipeIngredient[]
  steps: readonly string[]
  tags: readonly RecipeTagId[]
  childServing?: ChildServingGuide
}

function recipe(seed: RecipeSeed): RecipeDef {
  return {
    version: 1,
    servings: 2,
    // 材料は辞書の ID だけで組んでいる（型で検査）ため、アレルゲンは辞書から導出できる。
    allergenStatus: "from_ingredients",
    source: { kind: "irori_original", note: RECIPE_SOURCE_NOTE },
    ...seed,
  }
}

