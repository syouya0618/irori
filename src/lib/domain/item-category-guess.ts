/** 小書き仮名→大書き仮名（半角カナ由来の偽小書き「キヤベツ」等を「キャベツ」と同一視する） */
const SMALL_TO_LARGE_KANA: Record<string, string> = {
  "ぁ": "あ", "ぃ": "い", "ぅ": "う", "ぇ": "え", "ぉ": "お",
  "っ": "つ", "ゃ": "や", "ゅ": "ゆ", "ょ": "よ", "ゎ": "わ",
  "ゕ": "か", "ゖ": "け",
}

/**
 * 照合専用の正規化（表示名は変えず、キーワードと品名の両辺へ同じ変換を掛けて比較する）。
 * NFKC → 空白（半角/全角）・中点除去 → カタカナ→ひらがな折り畳み → 小書き仮名→大書き。
 * NFKC はカナ⇄かなを畳まず、OCR は字間に偽スペースや偽の大書き仮名を混ぜるため、
 * カタカナ主流のレシート品名を漢字/ひらがなのキーワードへ寄せるにはこの fold が要る。
 */
function fold(input: string): string {
  const nfkc = input.normalize("NFKC")
  let out = ""
  for (const ch of nfkc) {
    // 空白（半角/全角）と中点は除去（OCR の偽スペース対策）
    if (/\s/.test(ch) || ch === "・") continue
    const code = ch.codePointAt(0)!
    // カタカナ（U+30A1〜U+30F6）はひらがなへ。範囲外（ー・ヷ〜ヺ等）は素通し
    if (code >= 0x30a1 && code <= 0x30f6) {
      const hira = String.fromCodePoint(code - 0x60)
      out += SMALL_TO_LARGE_KANA[hira] ?? hira
    } else {
      out += SMALL_TO_LARGE_KANA[ch] ?? ch
    }
  }
  return out
}

/**
 * fold 済みキーワードを長さ降順（同長は表の定義順）で並べ、最長一致を先勝ちにする。
 * order は flatMap 後の通し番号＝表の定義順で、同長キーワードのタイブレークに使う。
 */
const FOLDED_KEYWORDS: { category: ItemCategory; folded: string; order: number }[] =
  CATEGORY_KEYWORDS.flatMap(([category, keywords]) =>
    keywords.map((keyword) => ({ category, folded: fold(keyword) })),
  )
    .map((entry, order) => ({ ...entry, order }))
    .sort((a, b) => b.folded.length - a.folded.length || a.order - b.order)

/**
 * 品名から在庫カテゴリを推測する。該当なしは "other_food"。
 * 結果は UI で編集可能な既定値として扱う。
 */
export function guessItemCategory(name: string): ItemCategory {
  const folded = fold(name)
  if (folded === "") return "other_food"

  for (const { category, folded: keyword } of FOLDED_KEYWORDS) {
    if (folded.includes(keyword)) return category
  }
  return "other_food"
}
