-- ============================================================
-- 授乳: 母乳サイクル（breast）を feeding_type ENUM に追加（パート1: ENUM拡張）
-- ============================================================

-- 母乳の授乳を「左右を何回ずつ吸わせたか」を持つ1行（サイクル行）で記録するための
-- 新しい種別。既存の breast_left / breast_right は過去データ用に残す（削除しない）。
--
-- NOTE: ALTER TYPE ... ADD VALUE はトランザクション外で実行される。
-- ADD VALUE と新値を参照する CHECK は同一トランザクション内で使えない
-- （`unsafe use of new value` で落ちる）ため、CHECK 制約は次のマイグレーション
-- 20260726100002 に分離する（20260721000001/2 と同じ分割）。
ALTER TYPE feeding_type ADD VALUE IF NOT EXISTS 'breast';
